#!/usr/bin/env node
// Builds js/levels-data.js: the campaign and Daily level tables that ship with the game.
// Deterministic: running it again produces the same file byte for byte.
//
//   node build-levels.mjs [web-dir] [campaignCount] [dailyCount]
//
// The tables are nothing more than makeLevel() run ahead of time for each number, so a
// level is the same whether it is read from a table or built on the device.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
/** The web folder: given on the command line, or the one named in app.config.json next to this folder. */
function findWebDir() {
  if (process.argv[2]) return resolve(process.argv[2]);
  const config = join(here, '..', 'app.config.json');
  return resolve(dirname(config), JSON.parse(readFileSync(config, 'utf8')).webDir);
}
const webDir = findWebDir();
const CAMPAIGN_COUNT = Number(process.argv[3] || 2000);
const DAILY_COUNT = Number(process.argv[4] || 2200);
const load = (f) => import(pathToFileURL(join(webDir, 'js', f)).href);

const { OPENING, campaignRecipe, dailyRecipe, makeLevel } = await load('gen.js');
const { formatLevel } = await load('engine.js');
const { DAILY_EPOCH, dayIndex } = await load('dates.js');

const make = (seed, recipe) => formatLevel(makeLevel(seed, recipe));

const t0 = Date.now();
const campaign = [];
for (let n = 1; n <= CAMPAIGN_COUNT; n++) {
  campaign.push(n <= OPENING.length ? OPENING[n - 1] : make(`c/${n}`, campaignRecipe(n)));
}
const epochDay = dayIndex(DAILY_EPOCH);
const daily = [];
for (let n = 1; n <= DAILY_COUNT; n++) {
  const weekday = new Date((epochDay + n - 1) * 86400000).getUTCDay();
  daily.push(make(`d/${n}`, dailyRecipe(n, weekday)));
}

const list = (items) => `[\n${items.map((s) => `  '${s}',`).join('\n')}\n]`;
const body =
  `// GENERATED by build-levels.mjs. Do not edit by hand.\n` +
  `// Level text format: see parseLevel() in engine.js.\n\n` +
  `/** Campaign levels 1..${campaign.length}. */\n` +
  `export const CAMPAIGN = ${list(campaign)};\n\n` +
  `/** Daily puzzles 1..${daily.length}, starting on ${DAILY_EPOCH}. */\n` +
  `export const DAILY = ${list(daily)};\n`;
writeFileSync(join(webDir, 'js', 'levels-data.js'), body);
console.log(`campaign ${campaign.length}, daily ${daily.length}, ${((Date.now() - t0) / 1000).toFixed(1)}s, ${(body.length / 1024).toFixed(0)} KB`);
